#!/usr/bin/env python3
"""Frozen independent Diameter wire driver using heimiricmr/Bromelia.

The driver is copied into a pinned Bromelia checkout and uses Bromelia's own
DiameterRequest/DiameterAnswer serialization and DiameterMessage parser.
Transport is real TCP.  No detector code or external test scores are imported.

This harness is deliberately simple: it tests wire-representation transfer,
not a complete EPC/HSS implementation.
"""
from __future__ import annotations

import argparse
import socket
import time

from bromelia import DiameterAnswer, DiameterMessage, DiameterRequest

APP_BASE = 0
APP_S6A = 16777251
CMD_CER = 257
CMD_DWR = 280
CMD_DPR = 282
CMD_AIR = 318
CMD_ULR = 316


def recv_exact(sock: socket.socket, n: int) -> bytes:
    chunks = []
    left = n
    while left:
        chunk = sock.recv(left)
        if not chunk:
            raise ConnectionError("peer closed connection")
        chunks.append(chunk)
        left -= len(chunk)
    return b"".join(chunks)


def recv_message(sock: socket.socket):
    header = recv_exact(sock, 20)
    length = int.from_bytes(header[1:4], "big")
    if length < 20 or length > 1_048_576:
        raise ValueError(f"invalid Diameter length {length}")
    body = recv_exact(sock, length - 20) if length > 20 else b""
    parsed = DiameterMessage.load(header + body)
    if len(parsed) != 1:
        raise RuntimeError(f"expected one Diameter message, got {len(parsed)}")
    return parsed[0]


def request(cmd: int, app: int) -> DiameterRequest:
    return DiameterRequest(command_code=cmd, application_id=app)


def answer(req) -> DiameterAnswer:
    return DiameterAnswer(header=req.header)


def exchange(sock: socket.socket, cmd: int, app: int) -> None:
    req = request(cmd, app)
    sock.sendall(req.dump())
    ans = recv_message(sock)
    if ans.get_command_code() != cmd or ans.get_application_id() != app:
        raise RuntimeError(
            f"unexpected answer cmd={ans.get_command_code()} "
            f"app={ans.get_application_id()}")


def run_server(host: str, port: int) -> None:
    srv = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    srv.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    srv.bind((host, port))
    srv.listen(16)
    print(f"Bromelia final wire server listening on {host}:{port}", flush=True)

    while True:
        conn, _ = srv.accept()
        conn.settimeout(30.0)
        try:
            while True:
                try:
                    req = recv_message(conn)
                except (ConnectionError, socket.timeout):
                    break
                conn.sendall(answer(req).dump())
        finally:
            conn.close()


def scenario_ops(name: str, count: int):
    n = max(1, int(count))
    if name == "benign_attach":
        return [CMD_AIR, CMD_ULR] * n, True
    if name == "benign_reauth":
        return [CMD_AIR] * n, True
    if name == "benign_update":
        return [CMD_ULR] * n, True
    if name == "air_flood":
        return [CMD_AIR] * n, False
    if name == "ulr_flood":
        return [CMD_ULR] * n, False
    if name == "mixed_flood":
        return [CMD_AIR if i % 2 == 0 else CMD_ULR for i in range(n)], False
    if name == "tracking_burst":
        return [
            CMD_AIR if i % 4 in (0, 1, 2) else CMD_ULR
            for i in range(n)
        ], False
    raise ValueError(f"unknown scenario {name!r}")


def run_client(
    host: str,
    port: int,
    scenario: str,
    count: int,
    delay_ms: int,
) -> None:
    ops, paced = scenario_ops(scenario, count)
    sock = socket.create_connection((host, port), timeout=10.0)
    sock.settimeout(30.0)
    delay_s = max(0, delay_ms) / 1000.0

    try:
        # RFC 6733 base-session traffic generated by Bromelia itself.
        exchange(sock, CMD_CER, APP_BASE)

        if paced:
            for i, cmd in enumerate(ops):
                exchange(sock, cmd, APP_S6A)
                if len(ops) >= 8 and i == len(ops) // 2:
                    exchange(sock, CMD_DWR, APP_BASE)
                if delay_s:
                    time.sleep(delay_s)
        else:
            # Send requests sequentially but without application pacing.
            # Keeping request/answer pairing avoids TCP socket-buffer artefacts
            # while preserving flood-like inter-message timing.
            for cmd in ops:
                exchange(sock, cmd, APP_S6A)

        exchange(sock, CMD_DPR, APP_BASE)
        time.sleep(0.12)
    finally:
        sock.close()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", choices=["server", "client"], required=True)
    ap.add_argument("--host", default="127.0.0.1")
    ap.add_argument("--port", type=int, default=3868)
    ap.add_argument("--scenario", default="benign_attach")
    ap.add_argument("--count", type=int, default=2)
    ap.add_argument("--delay-ms", type=int, default=600)
    args = ap.parse_args()

    if args.mode == "server":
        run_server(args.host, args.port)
    else:
        run_client(
            args.host, args.port, args.scenario, args.count, args.delay_ms)


if __name__ == "__main__":
    main()
